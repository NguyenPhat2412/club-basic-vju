// Single source of truth for TanStack Query keys: a typo in a root becomes a TS error.
// qk.x() -> ["x"] (prefix for invalidation); qk.x(a, b) -> ["x", a, b] (exact element order is preserved).
const key =
  <const R extends string>(root: R) =>
  <const T extends readonly unknown[]>(...rest: T): readonly [R, ...T] =>
    [root, ...rest] as const;

